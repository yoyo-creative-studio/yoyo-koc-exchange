BEGIN;

CREATE TABLE IF NOT EXISTS public.platform_admins (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  username TEXT NOT NULL,
  display_name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('platform_owner', 'project_owner', 'admin', 'operator', 'viewer')),
  password_salt TEXT,
  password_hash TEXT,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
  is_system_owner BOOLEAN NOT NULL DEFAULT false,
  created_by UUID REFERENCES public.platform_admins(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_login_at TIMESTAMPTZ,
  CHECK (username = lower(username)),
  CHECK (username ~ '^[a-z0-9][a-z0-9._-]{1,62}$'),
  CHECK (NOT is_system_owner OR role = 'platform_owner')
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_platform_admins_username_lower
  ON public.platform_admins(lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS uq_platform_admins_single_system_owner
  ON public.platform_admins(is_system_owner) WHERE is_system_owner = true;

CREATE TABLE IF NOT EXISTS public.platform_admin_project_access (
  admin_id UUID NOT NULL REFERENCES public.platform_admins(id) ON DELETE CASCADE,
  project_id UUID NOT NULL REFERENCES public.platform_projects(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (admin_id, project_id)
);

CREATE TABLE IF NOT EXISTS public.platform_admin_sessions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  admin_id UUID NOT NULL REFERENCES public.platform_admins(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_platform_admin_sessions_active
  ON public.platform_admin_sessions(token_hash, expires_at);

CREATE TABLE IF NOT EXISTS public.platform_admin_audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id UUID REFERENCES public.platform_admins(id) ON DELETE SET NULL,
  project_id UUID REFERENCES public.platform_projects(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'started' CHECK (status IN ('started', 'succeeded', 'failed')),
  metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_platform_admin_audit_project_time
  ON public.platform_admin_audit_log(project_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.protect_platform_system_owner()
RETURNS TRIGGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF OLD.is_system_owner AND (
    TG_OP = 'DELETE'
    OR NEW.is_system_owner IS DISTINCT FROM true
    OR NEW.role IS DISTINCT FROM 'platform_owner'
    OR NEW.status IS DISTINCT FROM 'active'
  ) THEN
    RAISE EXCEPTION 'The platform owner cannot be removed, disabled, or downgraded';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

DROP TRIGGER IF EXISTS trg_protect_platform_system_owner ON public.platform_admins;
CREATE TRIGGER trg_protect_platform_system_owner
BEFORE UPDATE OR DELETE ON public.platform_admins
FOR EACH ROW EXECUTE FUNCTION public.protect_platform_system_owner();

ALTER TABLE public.platform_admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.platform_admin_project_access ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.platform_admin_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.platform_admin_audit_log ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.platform_admins FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.platform_admin_project_access FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.platform_admin_sessions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.platform_admin_audit_log FROM PUBLIC, anon, authenticated;

COMMIT;
